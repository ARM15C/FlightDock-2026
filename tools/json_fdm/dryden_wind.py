#!/usr/bin/env python3
"""dryden_wind — seeded deterministic wind/turbulence for the JSON-lockstep FDM.

RESPONSIBILITY
    Produce an NED wind velocity disturbance to be applied INSIDE the FDM (the
    SIM_WIND_* path is bypassed under --model JSON, per SIM_JSON.cpp:405-406, so
    wind must move the TRUE vehicle from within the physics). DEFAULT-OFF: with no
    mean and no turbulence intensity it returns exactly zero (so wind-off cruise
    equivalence is byte-clean). When enabled it adds a mean wind plus a Dryden-style
    turbulence gust generated by a first-order forming filter driven by SEEDED
    Gaussian white noise — deterministic, fixed-step, NO wall-clock (research:
    rational-PSD linear filter; exact ZOH discretization preserves variance).
    NOTE (OMISSION_REGISTER O2): native SITL turbulence is a cruder non-deterministic
    IIR (rand()); J4A uses Dryden by design. The lateral/vertical axes use the
    first-order (u-axis) form; full Dryden v/w are 2nd-order — simplified for the
    J4A minimum and refined in J4B if crosswind work needs it.

PUBLIC API
    DrydenWind(mean_ned=(0,0,0), sigma=(0,0,0), length_scale=(200,200,50),
               airspeed=24.7, seed=20260622)
        .enabled: bool # False when default-off (zero mean + zero sigma)
        .update(dt) -> (wn, we, wd) # NED wind m/s; zeros when disabled
        .reset() # re-seed to initial, restoring determinism

SIDE EFFECTS
    None external. Owns one numpy Generator (seeded) and a 3-element filter state,
    both internal. No I/O, no wall-clock, no global RNG. No training/reward/
    observation/replay/env/fuser/controller/truth import.

CAPS
    file soft 200 / hard 300 LoC; function LoC cap 60.

COVERAGE
    tests/unit/test_json_fdm_dryden_wind.py (T12..T14).
"""
from __future__ import annotations

import math
from typing import Sequence, Tuple

import numpy as np


class DrydenWind:
    """Mean wind + seeded first-order Dryden turbulence (default-off)."""

    def __init__(self, mean_ned: Sequence[float] = (0.0, 0.0, 0.0),
                 sigma: Sequence[float] = (0.0, 0.0, 0.0),
                 length_scale: Sequence[float] = (200.0, 200.0, 50.0),
                 airspeed: float = 24.7, seed: int = 20260622) -> None:
        self.mean = np.array(mean_ned, dtype=float)
        self.sigma = np.array(sigma, dtype=float)
        self.length_scale = np.array(length_scale, dtype=float)
        self.airspeed = float(airspeed)
        self._seed = int(seed)
        self._rng = np.random.default_rng(self._seed)
        self._filt = np.zeros(3, dtype=float)
        self.turbulent = bool(np.any(self.sigma > 0.0))
        self.enabled = bool(self.turbulent or np.any(self.mean != 0.0))

    def reset(self) -> None:
        """Restore initial seed + zero filter state (determinism guarantee)."""
        self._rng = np.random.default_rng(self._seed)
        self._filt = np.zeros(3, dtype=float)

    def update(self, dt: float) -> Tuple[float, float, float]:
        """Advance one step; return NED wind (m/s). Zeros when disabled."""
        if not self.enabled:
            return (0.0, 0.0, 0.0)
        gust = np.zeros(3, dtype=float)
        if self.turbulent and dt > 0.0 and self.airspeed > 0.0:
            for i in range(3):
                li = self.length_scale[i]
                si = self.sigma[i]
                if si > 0.0 and li > 0.0:
                    # exact ZOH discretization of first-order Dryden/OU process:
                    # x[k] = b*x[k-1] + sigma*sqrt(1-b^2)*white, b = exp(-V*dt/L)
                    b = math.exp(-self.airspeed * dt / li)
                    white = float(self._rng.standard_normal())
                    self._filt[i] = b * self._filt[i] + si * math.sqrt(max(0.0, 1.0 - b * b)) * white
                    gust[i] = self._filt[i]
        w = self.mean + gust
        return (float(w[0]), float(w[1]), float(w[2]))
