#!/usr/bin/env python3
# =============================================================================
# RESPONSIBILITY: generate scripts/eval_venue_env.sh from the CONTRACT ITSELF
#   (env_contract.EVAL_REQUIRED / EVAL_FORBIDDEN), so a knob signed next month
#   appears in every live eval launcher without anyone editing a shell.
#
# WHY GENERATED AND NOT HAND-WRITTEN. Hand-listing knobs is the SEEDALLOC-759
#   defect class: a hardcoded list cannot see a requirement signed after it was
#   written. That is not hypothetical here -- [MEASURED 2026-08-20] ~135 shells
#   export at least one D7/EVAL knob and ZERO export FD_DEMOTE_TERMINALS, which
#   is exactly how ARMBDESC wave 1 refused on all 76 legs.
#
# WHY A SHARED INCLUDE AND NOT A SWEEP. Each gate spawns a NEW relay script
#   (w1418..w1423, 14 so far); the next gate writes w1424. Editing the past 14
#   changes nothing -- they have already flown. The requirement is that the
#   NEXT relay is born correct, which is a template problem.
#
# IT ALSO UNSETS. EVAL_FORBIDDEN knobs are actively cleared, not merely
#   omitted: a relay launched from a shell earlier used for training would
#   otherwise INHERIT FD_FORMATION_LOST_TERM and silently defeat the demoted
#   terminals (env_contract R8).
#
# PUBLIC API: render() -> str; main(argv) -> int. CLI: --check | --write.
# SIDE-EFFECTS: --write replaces scripts/eval_venue_env.sh. --check writes
#   nothing. No network, no spawn.
# EXIT: 0 in sync / written · 2 DRIFT (--check) -- caller must regenerate.
# CAPS: file soft 70 / hard 100 code-lines; function cap 35.
# COVERAGE: tests/unit/test_eval_venue_env.py, both directions.
# =============================================================================
"""Generate the shared EVAL venue env include. See header block above."""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEST = os.path.join(ROOT, "scripts", "eval_venue_env.sh")
sys.path.insert(0, ROOT)
from src.drl import env_contract as ec  # noqa: E402

BANNER = """\
# =============================================================================
# GENERATED BY tools/gen_eval_venue_env.py -- DO NOT HAND-EDIT.
# Regenerate with:  python tools/gen_eval_venue_env.py --write
# Verify with:      python tools/gen_eval_venue_env.py --check   (rc 2 = drift)
#
# Source this from every LIVE eval/exam launcher, BEFORE any leg is spawned:
#     source "$FLIGHTDOCK_ROOT/scripts/eval_venue_env.sh"
#
# Its contents are derived from env_contract.D7_REQUIRED, EVAL_REQUIRED and
# EVAL_FORBIDDEN, so a knob signed after this file was written still lands
# here. Do not add knobs by hand -- add them to the contract and regenerate.
# D7 added by RELAYD7-797 (2026-08-21): the a4 exam REFUSED on R1
# FD_SAFETY_TERMINALS because D7 lived only in hand-copied relay lines.
# =============================================================================
"""


def render():
    """The file contents. Deterministic: sorted, no timestamp, no host."""
    out = [BANNER, "\n# D7_REQUIRED -- role-agnostic; an eval leg missing any"
                   " of these REFUSES (env_contract R1).\n"]
    for key, val in sorted(ec.D7_REQUIRED.items()):
        out.append('export %s="%s"\n' % (key, val))
    out.append("\n# EVAL_REQUIRED -- an eval leg missing any of these"
               " REFUSES (env_contract R5).\n")
    for key, val in sorted(ec.EVAL_REQUIRED.items()):
        out.append('export %s="%s"\n' % (key, val))
    out.append("\n# EVAL_FORBIDDEN -- actively CLEARED, not merely omitted, so"
               " a shell\n# previously used for training cannot leak one in"
               " (env_contract R8).\n")
    for key in sorted(ec.EVAL_FORBIDDEN):
        out.append("unset %s\n" % key)
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    ap.add_argument("--dest", default=DEST)
    a = ap.parse_args(argv)
    want = render()
    if a.write:
        with open(a.dest, "w") as fh:
            fh.write(want)
        print("wrote %s (%d exports, %d unsets)"
              % (a.dest, len(ec.D7_REQUIRED) + len(ec.EVAL_REQUIRED),
                 len(ec.EVAL_FORBIDDEN)))
        return 0
    try:
        got = open(a.dest).read()
    except OSError as e:
        sys.stderr.write("DRIFT: cannot read %s: %s\n" % (a.dest, e))
        return 2
    if got != want:
        sys.stderr.write("DRIFT: %s is stale -- regenerate with --write\n"
                         % a.dest)
        return 2
    print("[eval_venue_env] in sync with the contract")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
